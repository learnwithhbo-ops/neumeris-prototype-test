  const FRA09 = window.RevilyFra09Approved;
  function dividesExactly(value, factor) {
    return Number.isInteger(value) && Number.isInteger(factor) && factor !== 0 && value % factor === 0;
}
  function isValidCommonFactor(fraction, factor) {
    return (factor > 1 &&
        dividesExactly(fraction.numerator, factor) &&
        dividesExactly(fraction.denominator, factor));
}
  function divideByGivenFactor(fraction, factor) {
    if (!isValidCommonFactor(fraction, factor)) {
        throw new Error(`Factor ${factor} does not divide ${fraction.numerator}/${fraction.denominator} exactly on both numbers.`);
    }
    return {
        numerator: fraction.numerator / factor,
        denominator: fraction.denominator / factor,
    };
}
  function fractionsEquivalent(a, b) {
    return (a.denominator !== 0 &&
        b.denominator !== 0 &&
        a.numerator * b.denominator === b.numerator * a.denominator);
}
  function classifyDirectFractionResponse(params) {
    const { original, factor, submitted } = params;
    if (!Number.isInteger(submitted.numerator) ||
        !Number.isInteger(submitted.denominator) ||
        submitted.denominator <= 0) {
        return { correct: false, errorFamily: "UNKNOWN" };
    }
    const expected = divideByGivenFactor(original, factor);
    if (submitted.numerator === expected.numerator &&
        submitted.denominator === expected.denominator) {
        return { correct: true };
    }
    if (submitted.numerator === expected.numerator &&
        submitted.denominator === original.denominator) {
        return { correct: false, errorFamily: "TOP_ONLY" };
    }
    if (submitted.numerator === original.numerator &&
        submitted.denominator === expected.denominator) {
        return { correct: false, errorFamily: "BOTTOM_ONLY" };
    }
    if (submitted.numerator === original.numerator - factor &&
        submitted.denominator === original.denominator - factor) {
        return { correct: false, errorFamily: "SUBTRACT" };
    }
    const topDivisor = submitted.numerator !== 0 && original.numerator % submitted.numerator === 0
        ? original.numerator / submitted.numerator
        : undefined;
    const bottomDivisor = submitted.denominator !== 0 &&
        original.denominator % submitted.denominator === 0
        ? original.denominator / submitted.denominator
        : undefined;
    if (topDivisor !== undefined &&
        bottomDivisor !== undefined &&
        topDivisor > 1 &&
        bottomDivisor > 1 &&
        topDivisor !== bottomDivisor) {
        return { correct: false, errorFamily: "MISMATCH" };
    }
    if (fractionsEquivalent(original, submitted)) {
        return {
            correct: false,
            errorFamily: "SKIPS_STEP",
            formSensitiveEquivalent: true,
        };
    }
    return { correct: false, errorFamily: "UNKNOWN" };
}
  function evaluateQuestionResponse(questionId, response) {
    const question = FRA09.questions.find((candidate) => candidate.id === questionId);
    if (!question)
        throw new Error(`Unknown FRA09 question: ${questionId}`);
    const evaluation = question.evaluation;
    if (evaluation.kind === "exact_given_factor_fraction") {
        if (typeof response !== "object" ||
            response === null ||
            !("numerator" in response) ||
            !("denominator" in response)) {
            return { correct: false, errorFamily: "UNKNOWN" };
        }
        return classifyDirectFractionResponse({
            original: question.visual.originalFraction,
            factor: question.visual.givenFactor,
            submitted: response,
        });
    }
    if (evaluation.kind === "missing_quotient") {
        if (typeof response !== "number" || !Number.isInteger(response)) {
            return { correct: false, errorFamily: "UNKNOWN" };
        }
        if (response === question.answer)
            return { correct: true };
        if (response === evaluation.unchangedValue) {
            return { correct: false, errorFamily: "BOTTOM_ONLY" };
        }
        if (response === evaluation.subtractionValue) {
            return { correct: false, errorFamily: "SUBTRACT" };
        }
        if (evaluation.neutralValues.includes(response)) {
            return { correct: false, errorFamily: "UNKNOWN_NEUTRAL" };
        }
        return { correct: false, errorFamily: "UNKNOWN" };
    }
    if (evaluation.kind === "single_choice") {
        if (typeof response !== "string") {
            return { correct: false, errorFamily: "UNKNOWN" };
        }
        if (response === question.answer)
            return { correct: true };
        const mapped = evaluation.errorFamilyByOption?.[response];
        return { correct: false, errorFamily: mapped ?? "UNKNOWN" };
    }
    return { correct: false, errorFamily: "UNKNOWN" };
}
  function selectOutcomeUtteranceIds(params) {
    const question = FRA09.questions.find((candidate) => candidate.id === params.questionId);
    if (!question)
        throw new Error(`Unknown FRA09 question: ${params.questionId}`);
    const feedback = question.feedback;
    if (params.evaluation.correct) {
        return [...feedback.correctUtteranceIds];
    }
    const specific = params.evaluation.errorFamily
        ? feedback.errorSpecificUtteranceIds?.[params.evaluation.errorFamily]
        : undefined;
    if (specific?.length) {
        return [...specific];
    }
    return [
        ...feedback.incorrectDefaultUtteranceIds,
    ];
}
